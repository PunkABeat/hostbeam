#!/usr/bin/env bash
# A local SSH host for development, in Docker. See docs/process/test-host.md.
#
# Exists because testing the beam path needs a real SSH server, and the only
# one around can go away. This one is disposable, works offline, and is
# reachable from the iPhone as well as the Mac.
set -euo pipefail

IMAGE="hostbeam-testhost"
ALIAS="${HOSTBEAM_TESTHOST_ALIAS:-hostbeam-testhost}"
PORT="${HOSTBEAM_TESTHOST_PORT:-2222}"
# Everything per-instance is keyed on the alias, so a second host is just a
# different ALIAS and PORT. Testing anything about *pairing* needs two hosts —
# the point of a remembered device is the second one taking one click — and
# aiming that at a real server to try a feature is the wrong trade.
NAME="$ALIAS"
# mosh's UDP ports, keyed on PORT like everything else so two hosts never
# collide. The same numbers inside and out: mosh-server reports the port it
# bound, and the client dials exactly that one.
MOSH_LO="${HOSTBEAM_TESTHOST_MOSH:-$((60000 + (PORT - 2222) * 10))}"
MOSH_HI=$((MOSH_LO + 9))
FOLDER="/tmp/hostbeam"
USER_NAME="dev"

STATE="${XDG_CONFIG_HOME:-$HOME/.config}/hostbeam-testhost"
KEY="$STATE/id_ed25519"
FRAGMENT="$STATE/$ALIAS.conf"        # matched by the Include glob below
KNOWN_HOSTS="$STATE/$ALIAS.known_hosts"
SSH_CONFIG="$HOME/.ssh/config"
INCLUDE_LINE="Include $STATE/*.conf"
DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"

die() { printf '  ✗ %s\n' "$*" >&2; exit 1; }
say() { printf '  %s\n' "$*"; }

command -v docker >/dev/null || die "docker not found"

# The address the *phone* will be told to use, so it cannot be a loopback:
# the QR carries this value, and "localhost" on the phone means the phone.
lan_ip() {
  local ip
  for iface in en0 en1 en2; do
    ip="$(ipconfig getifaddr "$iface" 2>/dev/null || true)"
    [ -n "$ip" ] && { printf '%s' "$ip"; return; }
  done
  printf '127.0.0.1'
}

ensure_key() {
  mkdir -p "$STATE"; chmod 700 "$STATE"
  [ -f "$KEY" ] || {
    ssh-keygen -q -t ed25519 -N '' -C "hostbeam-testhost" -f "$KEY"
    say "generated a dedicated key (never your own, never in the repo)"
  }
}

# One Include line, added once, as early as possible. Placement matters:
# ~/.ssh/config is first-obtained-wins, so a wildcard block above this could
# override the port and quietly send beams to the wrong place.
ensure_include() {
  [ -f "$SSH_CONFIG" ] || { mkdir -p "$HOME/.ssh"; chmod 700 "$HOME/.ssh"; touch "$SSH_CONFIG"; }
  grep -qxF "$INCLUDE_LINE" "$SSH_CONFIG" && return
  local tmp; tmp="$(mktemp)"
  { printf '# Hostbeam development SSH host (scripts/testhost.sh).\n'
    printf '# Must stay above any wildcard Host block: ssh is first-obtained-wins.\n'
    printf '%s\n\n' "$INCLUDE_LINE"
    cat "$SSH_CONFIG"
  } > "$tmp"
  cp "$SSH_CONFIG" "$SSH_CONFIG.bak-$(date +%Y%m%d%H%M%S)"
  # Write through, not mv: ~/.ssh/config is often a symlink into a dotfiles
  # repo, and mv would replace the link with a plain file.
  cat "$tmp" > "$SSH_CONFIG"; rm -f "$tmp"; chmod 600 "$SSH_CONFIG"
  say "added one Include line to ~/.ssh/config (backup alongside it)"
}

write_fragment() {
  local ip="$1"
  cat > "$FRAGMENT" <<EOF
# Generated by scripts/testhost.sh — edits are overwritten on \`up\`.
# HostName is the Mac's LAN address on purpose: the pairing QR hands this
# value to the phone, where a loopback address would mean the phone itself.
Host $ALIAS
    HostName $ip
    Port $PORT
    User $USER_NAME
    IdentityFile $KEY
    IdentitiesOnly yes
    UserKnownHostsFile $KNOWN_HOSTS
    StrictHostKeyChecking accept-new
EOF
  chmod 600 "$FRAGMENT"
}

running() { [ "$(docker inspect -f '{{.State.Running}}' "$NAME" 2>/dev/null || echo false)" = true ]; }

# The image is labelled with a hash of its build context, so editing the
# Dockerfile is enough to get a new one — before, `up` reused whatever image
# existed, and a new tool in the Dockerfile never reached anyone's host.
context_hash() { cat "$DIR"/scripts/testhost/* | shasum | cut -c1-12; }

ensure_image() {
  local want; want="$(context_hash)"
  [ "$(docker image inspect -f '{{index .Config.Labels "hostbeam.context"}}' "$IMAGE" 2>/dev/null)" = "$want" ] && return
  say "building the image (its Dockerfile changed, or there was none)…"
  docker build -q --label "hostbeam.context=$want" -t "$IMAGE" "$DIR/scripts/testhost" >/dev/null
}

cmd_up() {
  ensure_key
  ensure_image
  if running && [ "$(docker inspect -f '{{.Image}}' "$NAME")" = "$(docker image inspect -f '{{.Id}}' "$IMAGE")" ]; then
    say "already running"
  else
    # A container on an older image is replaced; its identity is on volumes.
    running && say "replacing the container with the new image (host key and authorized devices are kept)"
    docker rm -f "$NAME" >/dev/null 2>&1 || true
    docker run -d --name "$NAME" \
      -p "$PORT:2222" \
      -p "$MOSH_LO-$MOSH_HI:$MOSH_LO-$MOSH_HI/udp" \
      -v "$ALIAS-keys:/etc/ssh/keys" \
      -v "$ALIAS-home:/home/dev/.ssh" \
      -e AUTHORIZED_KEY="$(cat "$KEY.pub")" \
      "$IMAGE" >/dev/null
  fi
  ensure_include
  local ip; ip="$(lan_ip)"
  write_fragment "$ip"
  [ "$ip" = "127.0.0.1" ] && say "⚠ no LAN address found — the Mac can reach it, the iPhone cannot"
  # Wait for sshd rather than guess.
  for _ in $(seq 1 30); do
    ssh -o BatchMode=yes -o ConnectTimeout=2 "$ALIAS" true 2>/dev/null && break
    sleep 0.3
  done
  cmd_status
}

cmd_down() {
  docker rm -f "$NAME" >/dev/null 2>&1 && say "container removed" || say "not running"
  # Drop the host from ssh config so the app stops listing an unreachable box.
  # The Include line stays; its glob simply matches nothing now.
  rm -f "$FRAGMENT"
  say "host removed from ssh config (volumes kept — \`reset\` wipes them)"
}

cmd_reset() {
  cmd_down
  docker volume rm "$ALIAS-keys" "$ALIAS-home" >/dev/null 2>&1 || true
  # The local pin must go with it. Left behind, it makes the *next* `up`
  # fail as a host-key mismatch — correct behaviour from ssh, and a baffling
  # "reachable: NO" from a host that was just created.
  rm -f "$KNOWN_HOSTS"
  say "volumes wiped — the host key and every authorized device are gone"
  say "note: paired phones will report a host-key mismatch until re-trusted"
}

cmd_status() {
  if running; then
    say "container : running on port $PORT"
  else
    say "container : not running"; return 0
  fi
  [ -f "$FRAGMENT" ] || { say "ssh alias : not configured (run \`up\`)"; return 0; }
  local port; port="$(ssh -G "$ALIAS" 2>/dev/null | awk '/^port /{print $2}')"
  say "ssh alias : $ALIAS → $USER_NAME@$(ssh -G "$ALIAS" 2>/dev/null | awk '/^hostname /{print $2}'):$port"
  [ "$port" = "$PORT" ] || say "⚠ ssh resolves port $port, not $PORT — a wildcard Host block above the Include is overriding it"
  if ssh -o BatchMode=yes -o ConnectTimeout=5 "$ALIAS" true 2>/dev/null; then
    say "reachable : yes"
  else
    say "reachable : NO"; return 0
  fi
  say "host key  : $(docker exec "$NAME" ssh-keygen -lf /etc/ssh/keys/ssh_host_ed25519_key.pub 2>/dev/null | awk '{print $2}')"
  say "authorized:"
  docker exec "$NAME" sh -c 'while read -r l; do [ -n "$l" ] && printf "%s\n" "$l"; done < /home/dev/.ssh/authorized_keys' 2>/dev/null \
    | while read -r line; do
        printf '              %s  %s\n' \
          "$(printf '%s' "$line" | ssh-keygen -lf - 2>/dev/null | awk '{print $2}')" \
          "$(printf '%s' "$line" | awk '{print $3}')"
      done
  say "beamed    : $(docker exec "$NAME" sh -c "ls -1 $FOLDER 2>/dev/null | wc -l" | tr -d ' ') file(s) in $FOLDER"
  say "agent     : $(docker exec -u "$USER_NAME" "$NAME" sh -lc 'claude --version 2>/dev/null' | awk '{print "Claude Code " $1}'), tmux, mosh"
  say "mosh      : mosh -p $MOSH_LO:$MOSH_HI $ALIAS"
}

cmd_logs() { docker logs -f --tail 50 "$NAME"; }
cmd_clear() { docker exec "$NAME" sh -c "rm -f $FOLDER/*"; say "cleared $FOLDER"; }

case "${1:-status}" in
  up)     cmd_up ;;
  down)   cmd_down ;;
  reset)  cmd_reset ;;
  status) cmd_status ;;
  logs)   cmd_logs ;;
  clear)  cmd_clear ;;
  *) cat <<EOF
usage: scripts/testhost.sh <up|down|status|logs|clear|reset>

  up      start the host and add it to ~/.ssh/config
  down    stop it and remove it from ~/.ssh/config (keeps its identity)
  status  what it is, whether it answers, who may log in, what has landed
  logs    follow sshd (auth failures show the offered key fingerprint)
  clear   empty $FOLDER
  reset   down + wipe volumes; the host key and all authorized devices go

env: HOSTBEAM_TESTHOST_PORT (default 2222), HOSTBEAM_TESTHOST_ALIAS
     (default hostbeam-testhost). Both key the container, its volumes and its
     ssh entry, so a second host is one more invocation:
       HOSTBEAM_TESTHOST_ALIAS=hostbeam-testhost2 \\
       HOSTBEAM_TESTHOST_PORT=2223 scripts/testhost.sh up
EOF
    exit 1 ;;
esac
